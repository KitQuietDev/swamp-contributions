/**
 * Deploys and manages Authelia as a forward-auth gate in front of a
 * `traefik_stack` deployment. Genuinely coupled to Traefik — the
 * `forwardAuth` middleware definition Traefik routers reference lives in
 * Traefik's *own* dynamic config, not Authelia's — so `apply` here also
 * ensures that middleware block exists via `traefikDynamicConfigPath`.
 * That coupling is kept explicit (a parameter, documented) rather than
 * silent.
 *
 * Secrets (session, storage encryption, JWT, and — when `oidcEnabled` —
 * the OIDC hmac secret) are generated on the target host using Authelia's
 * own `authelia crypto rand --file` inside a throwaway container — the
 * values are written straight to files on the host and never captured
 * back over the SSH exec channel.
 *
 * `authBackend` selects between two mutually exclusive identity sources:
 * - `"file"` (default): `add-user` takes a pre-computed password *hash*,
 *   never a plaintext password — the human runs
 *   `authelia crypto hash generate argon2` themselves and hands back only
 *   the hash, exactly like setting this up by hand.
 * - `"ldap"`: identity lives in a paired `lldap_directory` instance
 *   instead — `add-user` is a no-op guard here (it throws, pointing at
 *   `lldap_directory`'s own `add-user`) since this package's `file`-backend
 *   user store isn't consulted at all once Authelia is LDAP-backed.
 *
 * `oidcEnabled` turns Authelia into an OpenID Connect provider (in
 * addition to its usual forward-auth role) so apps that support native
 * OIDC login (e.g. Immich, Audiobookshelf) can get real SSO instead of a
 * forward-auth redirect. The RSA issuer signing key is *not* generated by
 * this extension — Authelia's current schema requires it inline in YAML
 * (`identity_providers.oidc.jwks[].key`, no `_FILE`-env-var or per-item
 * secret mechanism exists for it, confirmed against Authelia's own
 * `configuration/identity-providers/openid-connect/provider.md`), so
 * embedding it here would mean reading a freshly-generated private key
 * back over the SSH exec channel — a real deviation from this file's
 * secrets discipline. Instead `oidcIssuerPrivateKeyPem` is supplied by the
 * caller via `${{ vault.get(vault, key) }}`, exactly like
 * `nodeIdentityContent` already is: generate it yourself
 * (`authelia crypto pair rsa generate`) and hand us only the PEM, never
 * generated-and-round-tripped by our code.
 *
 * `add-bypass-rule` exists because native mobile apps (discovered
 * building the reference deployment: Immich's and Audiobookshelf's iOS
 * apps) can't follow Authelia's redirect-to-a-login-page flow — they need
 * specific paths (typically `/api/*`, sometimes a few named ones like
 * `/status`/`/healthcheck`) bypassed. Bypass rules are inserted *before*
 * the catch-all policy rule, since access_control evaluates top-to-bottom
 * and first match wins.
 *
 * `check`/`apply` never regenerate `access_control.rules` or
 * `identity_providers.oidc.clients` wholesale — `mergedConfig` preserves
 * any access_control rule that isn't exactly the one managed catch-all
 * rule (identified by domain+policy shape, see `isManagedCatchAllRule`)
 * and preserves the entire existing OIDC clients list verbatim, so
 * `add-bypass-rule`/`add-oidc-client` output (or anything added by hand)
 * survives a re-`apply` instead of being silently dropped. Verified against
 * a real hand-configured instance during development: without the
 * access_control half of this, the first `apply` against an
 * already-running Authelia would have wiped two live mobile-app bypass
 * rules.
 *
 * @module
 */
